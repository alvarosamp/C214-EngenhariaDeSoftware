"""
Simple notification script used by GitHub Actions workflow.
It reads SMTP / recipient settings from environment variables and sends
a short email summarizing the pipeline results. The script does not
hardcode an email address — it must be provided through environment
variables in the Actions workflow (or locally for testing).

Environment variables used:
- RECIPIENT_EMAIL  (required)
- SMTP_SERVER      (required)
- SMTP_PORT        (optional, default 587)
- SMTP_USERNAME    (optional)
- SMTP_PASSWORD    (optional)
- TEST_STATUS      (optional)
- BUILD_STATUS     (optional)

If SMTP variables are not provided, the script will print the message
instead of sending email (useful for local runs).
"""
import os
import smtplib
from email.message import EmailMessage

RECIPIENT = os.getenv("RECIPIENT_EMAIL")
SMTP_SERVER = os.getenv("SMTP_SERVER")
SMTP_PORT = int(os.getenv("SMTP_PORT", "587"))
SMTP_USER = os.getenv("SMTP_USERNAME")
SMTP_PASS = os.getenv("SMTP_PASSWORD")
TEST_STATUS = os.getenv("TEST_STATUS", "unknown")
BUILD_STATUS = os.getenv("BUILD_STATUS", "unknown")

subject = f"Pipeline notification - tests: {TEST_STATUS}, build: {BUILD_STATUS}"
body = (
    f"Pipeline executed.\n\nTest job status: {TEST_STATUS}\nBuild job status: {BUILD_STATUS}\n"
    "This message was generated by scripts/notify.py"
)

if not RECIPIENT or not SMTP_SERVER:
    print("Recipient or SMTP server not set. Printing the notification instead:")
    print("Subject:", subject)
    print("Body:\n", body)
else:
    msg = EmailMessage()
    msg["Subject"] = subject
    msg["From"] = SMTP_USER if SMTP_USER else f"no-reply@{SMTP_SERVER}"
    msg["To"] = RECIPIENT
    msg.set_content(body)

    try:
        with smtplib.SMTP(SMTP_SERVER, SMTP_PORT, timeout=10) as s:
            s.starttls()
            if SMTP_USER and SMTP_PASS:
                s.login(SMTP_USER, SMTP_PASS)
            s.send_message(msg)
        print("Notification email sent to", RECIPIENT)
    except Exception as e:
        print("Failed to send email, printing message instead. Error:", e)
        print("Subject:", subject)
        print("Body:\n", body)
