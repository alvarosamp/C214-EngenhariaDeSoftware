#!/usr/bin/env bash
set -euo pipefail

# Simple script to send notification email from Ubuntu runner using swaks.
# Expects environment variables: RECIPIENT_EMAIL, SMTP_SERVER, SMTP_PORT, SMTP_USERNAME, SMTP_PASSWORD,
# TEST_STATUS, BUILD_STATUS. If SMTP vars are missing it will print the message instead.

RECIPIENT="${RECIPIENT_EMAIL:-alvaroscareli@gmail.com}"
SMTP_SERVER="${SMTP_SERVER:-smtp.office365.com}"
SMTP_PORT="${SMTP_PORT:-587}"
SMTP_USER="${SMTP_USERNAME:-vish88@outlook.com}"
SMTP_PASS="${SMTP_PASSWORD:-your-outlook-app-password}"  # Use app password for better security
TEST_STATUS="${TEST_STATUS:-unknown}"
BUILD_STATUS="${BUILD_STATUS:-unknown}"

SUBJECT="Pipeline notification - tests: ${TEST_STATUS}, build: ${BUILD_STATUS}"
BODY="Pipeline executed.\n\nTest job status: ${TEST_STATUS}\nBuild job status: ${BUILD_STATUS}\nThis message was generated by scripts/send_email_ubuntu.sh"

if [ -z "$RECIPIENT" ] || [ -z "$SMTP_SERVER" ]; then
  echo "Recipient or SMTP server not set. Printing the notification instead:"
  echo "Subject: $SUBJECT"
  echo -e "Body:\n$BODY"
  exit 0
fi

echo "Installing swaks (SMTP test tool) to send email..."
sudo apt-get update -qq
sudo apt-get install -y -qq swaks

ATTACH_ARGS=()
if [ -f "report.xml" ]; then
  echo "Found report.xml, will attach to email."
  ATTACH_ARGS=(--attach report.xml)
fi

echo "Sending email to $RECIPIENT via $SMTP_SERVER:$SMTP_PORT"
swaks --to "$RECIPIENT" \
      --from "${SMTP_USER:-no-reply@$SMTP_SERVER}" \
      --server "$SMTP_SERVER:$SMTP_PORT" \
      --auth LOGIN \
      --auth-user "$SMTP_USER" \
      --auth-password "$SMTP_PASS" \
      --tls \
      --header "Subject: $SUBJECT" \
      --body "$BODY" "${ATTACH_ARGS[@]:-}"

echo "swaks finished. If no error above, mail was accepted by SMTP server."
